# ------------------------------------------------------- нечёткое сравнение

def _ratio(a: str, b: str) -> float:
    return SequenceMatcher(None, a, b).ratio()


@lru_cache(maxsize=8192)
def _closest(word: str, vocab_key: int, cutoff: float, vocab_tuple: tuple):
    cands = [w for w in vocab_tuple
             if w[:1] == word[:1] and abs(len(w) - len(word)) <= 2]
    best = get_close_matches(word, cands, n=1, cutoff=cutoff)
    return best[0] if best else None


def correct_word(word: str, vocab, cutoff: float = 0.86):
    """Возвращает (исправленное_слово, было_ли_исправление)."""
    low = word.lower()
    if len(low) < 5 or not WORD_RE.match(word):
        return word, False
    if low in vocab:
        return word, False
    vocab_tuple = vocab if isinstance(vocab, tuple) else tuple(sorted(vocab))
    best = _closest(low, len(vocab_tuple), cutoff, vocab_tuple)
    if not best or best == low:
        return word, False
    fixed = best[:1].upper() + best[1:] if word[:1].isupper() else best
    return fixed, True


# ------------------------------------------------------- должности

class PositionSpeller:
    """Опечатки в должностях. extra_phrases — пользовательский справочник."""

    def __init__(self, extra_phrases=None):
        self.phrases = {}
        extra_words = set()
        for p in (extra_phrases or []):
            p = re.sub(r"\s+", " ", str(p or "")).strip()
            if p:
                self.phrases[p.lower()] = p
                extra_words.update(w.lower() for w in p.split() if WORD_RE.match(w))
        self.vocab = tuple(sorted(POSITION_VOCAB | extra_words))
        self.phrase_keys = tuple(sorted(self.phrases))
        self._memo = {}

    def correct(self, text: str):
        """Возвращает (исправленный_текст, список_правок)."""
        if text in self._memo:                 # в файлах много повторов
            return self._memo[text]
        result = self._correct(text)
        self._memo[text] = result
        return result

    def _correct(self, text: str):
        changes = []
        text = re.sub(r"\s+", " ", str(text or "")).strip()
        if not text:
            return text, changes

        low = text.lower()
        if self.phrase_keys and len(self.phrase_keys) <= 5000:
            if low in self.phrases:
                return self.phrases[low], changes
            best = get_close_matches(low, self.phrase_keys, n=1, cutoff=0.9)
            if best and _ratio(low, best[0]) >= 0.9:
                fixed = self.phrases[best[0]]
                if fixed.lower() != low:
                    changes.append(f"{text} → {fixed} (по справочнику)")
                return fixed, changes

        out = []
        for token in text.split(" "):
            core = token.strip(".,;:()«»\"'")
            tail = token[len(core):]
            low_core = core.lower()
            if low_core in POSITION_TYPOS:
                new = POSITION_TYPOS[low_core]
                new = new[:1].upper() + new[1:] if core[:1].isupper() else new
                changes.append(f"{core} → {new}")
                out.append(new + tail)
                continue
            new, changed = correct_word(core, self.vocab)
            if changed:
                changes.append(f"{core} → {new}")
            out.append(new + tail)
        return " ".join(out), changes


# ------------------------------------------------------- имена и отчества

def correct_name(name: str):
    return correct_word(name, tuple(sorted(NAMES)), cutoff=0.92)


def correct_patronymic(patr: str):
    if not patr or not WORD_RE.match(patr):
        return patr, False
    low = patr.lower()
    if low.endswith(VALID_PATRONYMIC_ENDINGS) or low in SHORT_PATRONYMICS:
        return patr, False              # шаблон соблюдён — не трогаем
    for bad, good in PATRONYMIC_TAIL_FIXES:
        if low.endswith(bad):
            fixed = low[: -len(bad)] + good
            return (fixed[:1].upper() + fixed[1:] if patr[:1].isupper() else fixed), True
    return correct_word(patr, tuple(sorted(PATRONYMICS)), cutoff=0.88)
