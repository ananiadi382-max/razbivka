def _make_patronymics():
    out = set()
    for n in MALE_NAMES:
        low = n.lower()
        if low.endswith("й"):
            stem = low[:-2] + "е" if low.endswith("ий") else low[:-1] + "е"
            out.add(stem + "вич")
            out.add(stem + "вна")
        elif low.endswith("ь"):
            out.add(low[:-1] + "евич")
            out.add(low[:-1] + "евна")
        elif low.endswith(("а", "я")):
            continue
        else:
            out.add(low + "ович")
            out.add(low + "овна")
